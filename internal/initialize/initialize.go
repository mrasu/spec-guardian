// Package initialize sets up SpecGuardian for a Go project.
package initialize

import (
	"bytes"
	_ "embed"
	"fmt"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/cockroachdb/errors"
	"github.com/mrasu/spec-guardian/internal/fizzbee"
)

//go:embed configuration.yml.tmpl
var configurationTemplateSource string

var configurationTemplate = template.Must(template.New("configuration").Parse(configurationTemplateSource))

// Run sets up SpecGuardian without replacing existing files.
func Run(projectDir, outputDir string) error {
	configPath := filepath.Join(projectDir, "specguardian.yml")
	entryPath := filepath.Join(projectDir, "conformance", "specguardian.go")
	if err := requireAbsentFiles(configPath, entryPath); err != nil {
		return err
	}
	if err := requireConformancePackage(filepath.Dir(entryPath)); err != nil {
		return err
	}

	config, err := readConfigurationSource(projectDir, outputDir)
	if err != nil {
		return err
	}
	return writeProjectFiles(configPath, entryPath, config)
}

func requireAbsentFiles(paths ...string) error {
	for _, path := range paths {
		if _, err := os.Lstat(path); err == nil {
			return fmt.Errorf("file already exists: %s", path)
		} else if !errors.Is(err, os.ErrNotExist) {
			return errors.Wrapf(err, "check %s", path)
		}
	}
	return nil
}

func requireConformancePackage(directory string) error {
	entries, err := os.ReadDir(directory)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return errors.Wrap(err, "read conformance directory")
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		path := filepath.Join(directory, entry.Name())
		file, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.PackageClauseOnly)
		if err != nil {
			return errors.Wrapf(err, "read package from %s", path)
		}
		name := file.Name.Name
		if name != "conformance" && !(strings.HasSuffix(entry.Name(), "_test.go") && name == "conformance_test") {
			return fmt.Errorf("package in %s is %q, want conformance", path, name)
		}
	}
	return nil
}

func readConfigurationSource(projectDir, outputDir string) ([]byte, error) {
	if !filepath.IsAbs(outputDir) {
		outputDir = filepath.Join(projectDir, outputDir)
	}
	cases, err := fizzbee.ReadActionCases(outputDir)
	if err != nil {
		return nil, err
	}
	relative, err := filepath.Rel(projectDir, outputDir)
	if err != nil {
		return nil, errors.Wrap(err, "resolve FizzBee output directory")
	}
	return toConfigurationSource(filepath.ToSlash(relative), cases)
}

func writeProjectFiles(configPath, entryPath string, config []byte) error {
	if err := os.MkdirAll(filepath.Dir(entryPath), 0755); err != nil {
		return errors.Wrap(err, "create conformance directory")
	}
	if err := createFile(configPath, config); err != nil {
		return err
	}
	entry := []byte(`// Code generated by spec-guardian. DO NOT EDIT.
package conformance

//go:generate go tool spec-guardian generate --config "../specguardian.yml"
`)
	if err := createFile(entryPath, entry); err != nil {
		return removeCreatedFile(configPath, err)
	}
	return nil
}

func toConfigurationSource(outputDir string, cases []fizzbee.ActionCase) ([]byte, error) {
	data := struct {
		OutputDir string
		Roles     map[string]map[string]bool
	}{OutputDir: outputDir, Roles: collectRoleFields(cases)}

	var source bytes.Buffer
	if err := configurationTemplate.Execute(&source, data); err != nil {
		return nil, errors.Wrap(err, "render configuration")
	}
	return source.Bytes(), nil
}

func collectRoleFields(cases []fizzbee.ActionCase) map[string]map[string]bool {
	roles := make(map[string]map[string]bool)
	for _, actionCase := range cases {
		for _, role := range actionCase.Input.Roles {
			if roles[role.Name] == nil {
				roles[role.Name] = make(map[string]bool)
			}
			for field := range role.Fields {
				roles[role.Name][field] = true
			}
		}
	}
	return roles
}

func createFile(path string, contents []byte) error {
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0644)
	if err != nil {
		return errors.Wrapf(err, "create %s", path)
	}

	_, writeErr := file.Write(contents)
	closeErr := file.Close()
	if writeErr != nil {
		return removeCreatedFile(path, errors.Wrapf(writeErr, "write %s", path))
	}
	if closeErr != nil {
		return removeCreatedFile(path, errors.Wrapf(closeErr, "close %s", path))
	}
	return nil
}

func removeCreatedFile(path string, cause error) error {
	if err := os.Remove(path); err != nil {
		return errors.WithSecondaryError(cause, errors.Wrapf(err, "remove incomplete file %s", path))
	}
	return cause
}
