func TestRun_CreatesConfigurationAndEntryPoint(t *testing.T) {
	projectDir := t.TempDir()
	outputDir, err := filepath.Abs("../fizzbee/testdata/read_db/fizzbee_output")
	require.NoError(t, err)
	require.NoError(t, Run(projectDir, outputDir))

	relative, err := filepath.Rel(projectDir, outputDir)
	require.NoError(t, err)
	config, err := os.ReadFile(filepath.Join(projectDir, "specguardian.yml"))
	require.NoError(t, err)
	assert.Equal(t, "version: \"0.1\"\nfizzbee_files:\n  - output_dir: \""+filepath.ToSlash(relative)+"\"\n    # Uncomment roles and fields after adding each field's type or compare: false with a reason.\n    # roles:\n    #   - name: \"DB\"\n    #     fields:\n    #       - name: \"value\"\n    #   - name: \"Reader\"\n    #     fields:\n    #       - name: \"status\"\n    #       - name: \"value\"\n", string(config))
	entry, err := os.ReadFile(filepath.Join(projectDir, "conformance", "specguardian.go"))
	require.NoError(t, err)
	assert.Equal(t, "// Code generated by spec-guardian. DO NOT EDIT.\npackage conformance\n\n//go:generate go tool spec-guardian generate --config \"../specguardian.yml\"\n", string(entry))
}

func TestRun_ConfigurationSupportsGenerate(t *testing.T) {
	projectDir := t.TempDir()
	outputDir, err := filepath.Abs("../fizzbee/testdata/read_db/fizzbee_output")
	require.NoError(t, err)
	require.NoError(t, Run(projectDir, outputDir))
	require.NoError(t, os.WriteFile(filepath.Join(projectDir, "go.mod"), []byte("module example.com/project\n\ngo 1.27.0\n"), 0644))
	entry, err := os.ReadFile(filepath.Join(projectDir, "conformance", "specguardian.go"))
	require.NoError(t, err)
	require.NoError(t, generate.Run(t.Context(), generate.Options{ConfigPath: filepath.Join(projectDir, "specguardian.yml")}))
	regeneratedEntry, err := os.ReadFile(filepath.Join(projectDir, "conformance", "specguardian.go"))
	require.NoError(t, err)
	assert.Equal(t, entry, regeneratedEntry)
}

func TestRun_RegenerationPreservesFiles(t *testing.T) {
	projectDir := t.TempDir()
	outputDir, err := filepath.Abs("../fizzbee/testdata/read_db/fizzbee_output")
	require.NoError(t, err)
	require.NoError(t, Run(projectDir, outputDir))
	require.NoError(t, os.WriteFile(filepath.Join(projectDir, "go.mod"), []byte("module example.com/project\n\ngo 1.27.0\n"), 0644))
	require.NoError(t, generate.Run(t.Context(), generate.Options{ConfigPath: filepath.Join(projectDir, "specguardian.yml")}))
	firstGeneration := readProjectFiles(t, projectDir)
	require.NoError(t, generate.Run(t.Context(), generate.Options{ConfigPath: filepath.Join(projectDir, "specguardian.yml")}))
	assert.Equal(t, firstGeneration, readProjectFiles(t, projectDir))
}

func TestRun_RejectsConflictingConformancePackage(t *testing.T) {
	projectDir := t.TempDir()
	directory := filepath.Join(projectDir, "conformance")
	require.NoError(t, os.MkdirAll(directory, 0755))
	path := filepath.Join(directory, "helper.go")
	require.NoError(t, os.WriteFile(path, []byte("package checks\n"), 0644))

	require.ErrorContains(t, Run(projectDir, "missing-artifacts"), "want conformance")
	files := readProjectFiles(t, projectDir)
	assert.Equal(t, map[string]string{path: "package checks\n"}, files)
}

func readProjectFiles(t *testing.T, directory string) map[string]string {
	t.Helper()
	files := make(map[string]string)
	err := filepath.WalkDir(directory, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		contents, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		files[path] = string(contents)
		return nil
	})
	require.NoError(t, err)
	return files
}

func TestRun_PreservesExistingFiles(t *testing.T) {
	tests := []struct {
		name  string
		path  string
		other string
	}{
		{name: "configuration", path: "specguardian.yml", other: "conformance/specguardian.go"},
		{name: "entry point", path: "conformance/specguardian.go", other: "specguardian.yml"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			projectDir := t.TempDir()
			path := filepath.Join(projectDir, tt.path)
			require.NoError(t, os.MkdirAll(filepath.Dir(path), 0755))
			require.NoError(t, os.WriteFile(path, []byte("keep me"), 0644))
			err := Run(projectDir, "missing-artifacts")
			require.ErrorContains(t, err, "file already exists")
			contents, err := os.ReadFile(path)
			require.NoError(t, err)
			assert.Equal(t, "keep me", string(contents))
			_, err = os.Stat(filepath.Join(projectDir, tt.other))
			assert.True(t, os.IsNotExist(err))
		})
	}
}

func TestRun_InvalidArtifactsCreatesNoFiles(t *testing.T) {
	projectDir := t.TempDir()
	require.Error(t, Run(projectDir, "missing-artifacts"))
	entries, err := os.ReadDir(projectDir)
	require.NoError(t, err)
	assert.Empty(t, entries)
}

func TestWriteProjectFiles_EntryFailureRemovesCreatedConfiguration(t *testing.T) {
	projectDir := t.TempDir()
	configPath := filepath.Join(projectDir, "specguardian.yml")
	entryPath := filepath.Join(projectDir, "conformance", "specguardian.go")
	require.NoError(t, os.MkdirAll(filepath.Dir(entryPath), 0755))
	require.NoError(t, os.WriteFile(entryPath, []byte("keep me"), 0644))

	err := writeProjectFiles(configPath, entryPath, []byte("new configuration"))
	require.ErrorIs(t, err, os.ErrExist)
	_, err = os.Stat(configPath)
	assert.True(t, os.IsNotExist(err))
	entry, err := os.ReadFile(entryPath)
	require.NoError(t, err)
	assert.Equal(t, "keep me", string(entry))
}
